INSERT INTO ACCOUNTS (
    ACCOUNT_ID,
    CUSTOMER_ID,
    ACCOUNT_TYPE,
    CURRENCY,
    OPEN_DATE,
    BALANCE,
    STATUS
)
SELECT
    'A' || LPAD(20000 + ROW_NUMBER() OVER (ORDER BY SEQ4()), 6, '0')
        AS ACCOUNT_ID,

    c.CUSTOMER_ID,

    CASE UNIFORM(1,3,RANDOM())
        WHEN 1 THEN 'SAVINGS'
        WHEN 2 THEN 'CURRENT'
        ELSE 'CREDIT'
    END AS ACCOUNT_TYPE,

    CASE c.COUNTRY
        WHEN 'India' THEN 'INR'
        WHEN 'Singapore' THEN 'SGD'
        WHEN 'Germany' THEN 'EUR'
        WHEN 'United Kingdom' THEN 'GBP'
        ELSE 'AED'
    END AS CURRENCY,

    DATEADD(
        DAY,
        -UNIFORM(30,2200,RANDOM()),
        CURRENT_DATE()
    ) AS OPEN_DATE,

    ROUND(
        UNIFORM(10000,5000000,RANDOM()),
        2
    ) AS BALANCE,

    CASE
        WHEN UNIFORM(1,100,RANDOM()) <= 3 THEN 'BLOCKED'
        ELSE 'ACTIVE'
    END AS STATUS

FROM CUSTOMERS c
CROSS JOIN TABLE(GENERATOR(ROWCOUNT => 2));

SELECT
    COUNT(*) AS TOTAL_ACCOUNTS,
    COUNT(DISTINCT ACCOUNT_ID) AS UNIQUE_ACCOUNTS,
    COUNT(DISTINCT CUSTOMER_ID) AS CUSTOMERS_WITH_ACCOUNTS
FROM ACCOUNTS;

SELECT *
