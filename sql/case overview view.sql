USE DATABASE RFR_COPILOT;
USE SCHEMA ANALYTICS;
USE WAREHOUSE RFR_WH;

CREATE OR REPLACE VIEW RISK_CASE_OVERVIEW AS
SELECT
    f.FINDING_ID,
    f.CUSTOMER_ID,
    f.ACCOUNT_ID,

    c.CUSTOMER_NAME,
    c.COUNTRY AS CUSTOMER_COUNTRY,
    c.CUSTOMER_TYPE,
    c.CUSTOMER_RISK_LEVEL,
    c.ANNUAL_INCOME,
    c.KYC_STATUS,
    c.PEP_FLAG,

    a.ACCOUNT_TYPE,
    a.CURRENCY,
    a.BALANCE,
    a.STATUS AS ACCOUNT_STATUS,

    f.FINDING_TYPE,
    f.RISK_LEVEL,
    f.RISK_SCORE,
    f.SIGNAL_COUNT,
    f.SIGNAL_TYPES,

    f.FINDING_TITLE,
    f.FINDING_SUMMARY,
    f.RECOMMENDED_ACTION,
    f.STATUS AS FINDING_STATUS,
    f.CREATED_AT

FROM RISK_FINDINGS f

LEFT JOIN RAW.CUSTOMERS c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID

LEFT JOIN RAW.ACCOUNTS a
    ON f.ACCOUNT_ID = a.ACCOUNT_ID;


CREATE OR REPLACE VIEW RISK_SIGNAL_EVIDENCE AS
SELECT
    rs.SIGNAL_ID,
    rs.CUSTOMER_ID,
    rs.ACCOUNT_ID,
    rs.TRANSACTION_ID,

    rs.SIGNAL_TYPE,
    rs.SIGNAL_SEVERITY,
    rs.SIGNAL_SCORE,
    rs.DETECTED_AT,
    rs.EVIDENCE AS SIGNAL_EVIDENCE,

    t.TRANSACTION_TIMESTAMP,
    t.AMOUNT,
    t.CURRENCY,
    t.TRANSACTION_TYPE,
    t.CHANNEL,
    t.MERCHANT,
    t.COUNTRY AS TRANSACTION_COUNTRY,

    c.COUNTRY AS CUSTOMER_HOME_COUNTRY,
    c.CUSTOMER_TYPE,
    c.CUSTOMER_RISK_LEVEL

FROM RISK_SIGNALS rs

LEFT JOIN RAW.TRANSACTIONS t
    ON rs.TRANSACTION_ID = t.TRANSACTION_ID

LEFT JOIN RAW.CUSTOMERS c
    ON rs.CUSTOMER_ID = c.CUSTOMER_ID;


SELECT
    FINDING_ID,
    CUSTOMER_ID,
    ACCOUNT_ID,
    RISK_LEVEL,
    RISK_SCORE,
    SIGNAL_COUNT,
    SIGNAL_TYPES,
    FINDING_SUMMARY,
    RECOMMENDED_ACTION
FROM ANALYTICS.RISK_CASE_OVERVIEW
WHERE CUSTOMER_ID = 'C00506';


SELECT
    TRANSACTION_ID,
    SIGNAL_TYPE,
    SIGNAL_SEVERITY,
    SIGNAL_SCORE,
    TRANSACTION_TIMESTAMP,
    AMOUNT,
    TRANSACTION_COUNTRY,
    SIGNAL_EVIDENCE
FROM ANALYTICS.RISK_SIGNAL_EVIDENCE
WHERE CUSTOMER_ID = 'C00506'
ORDER BY TRANSACTION_TIMESTAMP;


