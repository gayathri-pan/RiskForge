WITH historical_daily AS (

    SELECT
        CUSTOMER_ID,
        DATE_TRUNC(
            'DAY',
            TRANSACTION_TIMESTAMP
        ) AS TX_DATE,

        SUM(AMOUNT) AS DAILY_AMOUNT

    FROM RFR_COPILOT.RAW.TRANSACTIONS

    WHERE TRANSACTION_ID NOT LIKE 'SC%'

    GROUP BY
        CUSTOMER_ID,
        DATE_TRUNC(
            'DAY',
            TRANSACTION_TIMESTAMP
        )
),

customer_behavior AS (

    SELECT
        CUSTOMER_ID,

        AVG(DAILY_AMOUNT) AS HISTORICAL_DAILY_AVG,

        STDDEV_SAMP(DAILY_AMOUNT) AS HISTORICAL_DAILY_STDDEV,

        COUNT(*) AS HISTORICAL_DAYS

    FROM historical_daily

    GROUP BY CUSTOMER_ID
),

scenario_daily AS (

    SELECT
        CUSTOMER_ID,

        ACCOUNT_ID,

        TRANSACTION_ID,

        TRANSACTION_TIMESTAMP,

        AMOUNT

    FROM RFR_COPILOT.RAW.TRANSACTIONS

    WHERE TRANSACTION_ID LIKE 'SC%'

),

behavior_scores AS (

    SELECT
        s.TRANSACTION_ID,
        s.CUSTOMER_ID,
        s.ACCOUNT_ID,
        s.AMOUNT,

        c.HISTORICAL_DAILY_AVG,
        c.HISTORICAL_DAILY_STDDEV,
        c.HISTORICAL_DAYS,

        CASE
            WHEN c.HISTORICAL_DAILY_STDDEV > 0
            THEN
                ABS(
                    (
                        s.AMOUNT
                        - c.HISTORICAL_DAILY_AVG
                    )
                    /
                    c.HISTORICAL_DAILY_STDDEV
                )
            ELSE 0
        END AS Z_SCORE

    FROM scenario_daily s

    JOIN customer_behavior c
        ON s.CUSTOMER_ID = c.CUSTOMER_ID
)

SELECT
    'BEH_' || TRANSACTION_ID AS SIGNAL_ID,

    CUSTOMER_ID,

    ACCOUNT_ID,

    TRANSACTION_ID,

    'BEHAVIORAL_ANOMALY' AS SIGNAL_TYPE,

    CASE
        WHEN Z_SCORE >= 6 THEN 'CRITICAL'
        WHEN Z_SCORE >= 4 THEN 'HIGH'
        ELSE 'MEDIUM'
    END AS SIGNAL_SEVERITY,

    LEAST(
        100,
        ROUND(Z_SCORE * 10, 2)
    ) AS SIGNAL_SCORE,

    'Current transaction amount: '
    || ROUND(AMOUNT,2)
    || '; Historical daily average: '
    || ROUND(HISTORICAL_DAILY_AVG,2)
    || '; Historical daily stddev: '
    || ROUND(HISTORICAL_DAILY_STDDEV,2)
    || '; Historical active days: '
    || HISTORICAL_DAYS
    || '; Behavioral z-score: '
    || ROUND(Z_SCORE,2)

FROM behavior_scores

WHERE HISTORICAL_DAYS >= 10
  AND Z_SCORE >= 3;


