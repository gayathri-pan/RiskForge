WITH velocity AS (
    SELECT
        t.CUSTOMER_ID,
        t.ACCOUNT_ID,
        t.TRANSACTION_ID,
        t.TRANSACTION_TIMESTAMP,
        COUNT(*) OVER (
            PARTITION BY t.CUSTOMER_ID
            ORDER BY t.TRANSACTION_TIMESTAMP
            RANGE BETWEEN INTERVAL '15 MINUTE' PRECEDING
                      AND CURRENT ROW
        ) AS TX_COUNT
    FROM RAW.TRANSACTIONS t
)

SELECT
    'VEL_' || TRANSACTION_ID,
    CUSTOMER_ID,
    ACCOUNT_ID,
    TRANSACTION_ID,
    'TRANSACTION_VELOCITY',

    CASE
        WHEN TX_COUNT >= 10 THEN 'CRITICAL'
        WHEN TX_COUNT >= 7 THEN 'HIGH'
        ELSE 'MEDIUM'
    END,

    LEAST(TX_COUNT * 10, 100),

    'Transactions in previous 15 minutes: '
    || TX_COUNT
    || '; Trigger transaction: '
    || TRANSACTION_ID

FROM velocity
WHERE TX_COUNT >= 5;

