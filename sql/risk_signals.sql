WITH historical_baseline AS (

    SELECT
        CUSTOMER_ID,
        AVG(AMOUNT) AS HISTORICAL_AVG,
        STDDEV_SAMP(AMOUNT) AS HISTORICAL_STDDEV,
        COUNT(*) AS HISTORICAL_COUNT
    FROM RFR_COPILOT.RAW.TRANSACTIONS
    WHERE TRANSACTION_ID NOT LIKE 'SC%'
    GROUP BY CUSTOMER_ID
),

candidate_transactions AS (

    SELECT
        t.TRANSACTION_ID,
        t.CUSTOMER_ID,
        t.ACCOUNT_ID,
        t.AMOUNT,
        h.HISTORICAL_AVG,
        h.HISTORICAL_STDDEV,
        h.HISTORICAL_COUNT,

        CASE
            WHEN h.HISTORICAL_STDDEV > 0 THEN
                ABS(
                    (t.AMOUNT - h.HISTORICAL_AVG)
                    / h.HISTORICAL_STDDEV
                )
            ELSE 0
        END AS Z_SCORE

    FROM RFR_COPILOT.RAW.TRANSACTIONS t

    JOIN historical_baseline h
        ON t.CUSTOMER_ID = h.CUSTOMER_ID

    WHERE t.TRANSACTION_ID LIKE 'SC%'
)

SELECT
    'AMT_' || TRANSACTION_ID AS SIGNAL_ID,

    CUSTOMER_ID,

    ACCOUNT_ID,

    TRANSACTION_ID,

    'AMOUNT_ANOMALY' AS SIGNAL_TYPE,

    CASE
        WHEN Z_SCORE >= 6 THEN 'CRITICAL'
        WHEN Z_SCORE >= 4 THEN 'HIGH'
        ELSE 'MEDIUM'
    END AS SIGNAL_SEVERITY,

    LEAST(100, ROUND(Z_SCORE * 10, 2)) AS SIGNAL_SCORE,

    'Current amount: '
    || ROUND(AMOUNT,2)
    || '; Historical average: '
    || ROUND(HISTORICAL_AVG,2)
    || '; Historical stddev: '
    || ROUND(HISTORICAL_STDDEV,2)
    || '; Historical transactions: '
    || HISTORICAL_COUNT
    || '; Z-score: '
    || ROUND(Z_SCORE,2)

FROM candidate_transactions

WHERE HISTORICAL_COUNT >= 10
  AND Z_SCORE >= 3;


