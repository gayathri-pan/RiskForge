WITH near_threshold AS (

    SELECT
        t.TRANSACTION_ID,
        t.CUSTOMER_ID,
        t.ACCOUNT_ID,
        t.TRANSACTION_TIMESTAMP,
        t.AMOUNT,

        COUNT(*) OVER (
            PARTITION BY t.CUSTOMER_ID, t.ACCOUNT_ID
            ORDER BY t.TRANSACTION_TIMESTAMP
            RANGE BETWEEN INTERVAL '30 MINUTE' PRECEDING
                      AND CURRENT ROW
        ) AS NEAR_THRESHOLD_COUNT

    FROM RFR_COPILOT.RAW.TRANSACTIONS t

    WHERE t.AMOUNT >= 90000
      AND t.AMOUNT < 100000
)

SELECT
    'STR_' || TRANSACTION_ID AS SIGNAL_ID,

    CUSTOMER_ID,

    ACCOUNT_ID,

    TRANSACTION_ID,

    'STRUCTURING' AS SIGNAL_TYPE,

    CASE
        WHEN NEAR_THRESHOLD_COUNT >= 5 THEN 'CRITICAL'
        WHEN NEAR_THRESHOLD_COUNT >= 4 THEN 'HIGH'
        ELSE 'MEDIUM'
    END AS SIGNAL_SEVERITY,

    LEAST(
        100,
        NEAR_THRESHOLD_COUNT * 20
    ) AS SIGNAL_SCORE,

    'Near-threshold transactions: '
    || NEAR_THRESHOLD_COUNT
    || '; Threshold: 100000; Window: 30 minutes'
    || '; Trigger amount: '
    || ROUND(AMOUNT,2)

FROM near_threshold

WHERE NEAR_THRESHOLD_COUNT >= 3;

