WITH geo_windows AS (

    SELECT
        t1.TRANSACTION_ID,
        t1.CUSTOMER_ID,
        t1.ACCOUNT_ID,
        t1.TRANSACTION_TIMESTAMP,
        t1.COUNTRY,

        COUNT(DISTINCT t2.COUNTRY) AS DISTINCT_COUNTRIES_60M

    FROM RFR_COPILOT.RAW.TRANSACTIONS t1

    JOIN RFR_COPILOT.RAW.TRANSACTIONS t2
        ON t1.CUSTOMER_ID = t2.CUSTOMER_ID
       AND t2.TRANSACTION_TIMESTAMP
           BETWEEN DATEADD(
               MINUTE,
               -60,
               t1.TRANSACTION_TIMESTAMP
           )
           AND t1.TRANSACTION_TIMESTAMP

    GROUP BY
        t1.TRANSACTION_ID,
        t1.CUSTOMER_ID,
        t1.ACCOUNT_ID,
        t1.TRANSACTION_TIMESTAMP,
        t1.COUNTRY
)

SELECT
    'GEO_' || TRANSACTION_ID AS SIGNAL_ID,

    CUSTOMER_ID,

    ACCOUNT_ID,

    TRANSACTION_ID,

    'GEOGRAPHIC_ANOMALY' AS SIGNAL_TYPE,

    CASE
        WHEN DISTINCT_COUNTRIES_60M >= 4 THEN 'CRITICAL'
        ELSE 'HIGH'
    END AS SIGNAL_SEVERITY,

    CASE
        WHEN DISTINCT_COUNTRIES_60M >= 4 THEN 100
        ELSE 75
    END AS SIGNAL_SCORE,

    'Distinct countries in previous 60 minutes: '
    || DISTINCT_COUNTRIES_60M
    || '; Current country: '
    || COUNTRY
    || '; Transaction: '
    || TRANSACTION_ID

FROM geo_windows

WHERE DISTINCT_COUNTRIES_60M >= 3;


