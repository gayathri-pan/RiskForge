    SIGNAL_SCORE,
    EVIDENCE
FROM ANALYTICS.RISK_SIGNALS
WHERE SIGNAL_TYPE = 'STRUCTURING'
ORDER BY CUSTOMER_ID, TRANSACTION_ID;

/*

Geographic anomaly detector - 3 or more distinct transaction countries for the same customer within 60 minutes → geographic anomaly.

*/

USE DATABASE RFR_COPILOT;
